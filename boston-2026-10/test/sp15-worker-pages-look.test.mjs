// SP15 (SPEC-save-offer-production.md § 10.3): the Worker's pages in the site's look. Every page src/worker/pages.js
// page() draws (the saved offer and its ended and unknown forms, the confirmation and its answers, GONE, TOO_MANY):
//   - one head, as build.mjs's privacyPage gives /privacy/: the template's :root tokens and @font-face rules (the fonts
//     from the site's own /fonts/), then src/worker/page.css's rules. A Worker cannot read the template at run time, so
//     the head's style is src/worker/page-style.json, DERIVED by `npm run worker:style` (scripts/worker-style.mjs): the
//     case fails when it differs from its sources, as M17 does for the emails' tokens;
//   - Fit AF's logo first in the page's one column, linking to /; the content in that column (max 680 px, 16 px gutters);
//   - the saved offer's one action (Build my plan) the page's orange button, at least 64 CSS px tall (its box is measured
//     in Chrome: tools/storybook's wp-chrome case); every other page's link back the quieter style;
//   - ⛔ nothing the pages say changes: each page's words are cc1d2bb's (the contract's own commit), page by page;
//   - every pair the pages draw is in src/contrast-pairs.json ("build": "worker") and passes.
import test, { after } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { ROOT } from "../build.mjs";
import { measure } from "../scripts/contrast.mjs";
import { pageText } from "./sp-production.mjs";
import { headOf, packageAt, workerPages } from "./sp-worker-pages.mjs";

/** The contract's own commit (§ 10.3 written, none of its code). */
const BASE = "cc1d2bb";
const base = await packageAt(BASE);
after(() => base.dispose());
const pages = await workerPages();
const PAGE_CSS = join(ROOT, "src", "worker", "page.css");

test("SP15: src/worker/page-style.json is derived from the template, src/save/style.css's DRAFT token and src/worker/page.css", async () => {
  const { workerStyleFile, serialise, PAGE_STYLE } = await import("../scripts/worker-style.mjs");
  const committed = await readFile(PAGE_STYLE, "utf8");
  assert.equal(committed, serialise(await workerStyleFile()), "regenerated by npm run worker:style, never by hand");
  const { css } = JSON.parse(committed);
  const template = await readFile(join(ROOT, "src", "template.html"), "utf8");
  assert.ok(css.includes(/:root\s*\{[^{}]*\}/.exec(template)[0]), "the template's :root, as written");
  const faces = template.match(/^@font-face \{.*\}$/gm);
  assert.ok(faces.length >= 4, "control: the template's font faces");
  for (const face of faces) assert.ok(css.includes(face.replace("{{ASSET_PREFIX}}", "/")), "each font face, its file from the site's /fonts/");
});

test("SP15: every Worker page carries the same head (its title apart): the site's look, in its <style>", async () => {
  const { css } = JSON.parse(await readFile(join(ROOT, "src", "worker", "page-style.json"), "utf8"));
  const heads = Object.entries(pages).map(([name, { html }]) => [name, headOf(html)]);
  for (const [name, head] of heads) {
    assert.ok(head.includes(`<style>\n${css}\n</style>`), `${name}: the derived style`);
    assert.equal(head, heads[0][1], `${name}: the same head as ${heads[0][0]}`);
  }
});

test("SP15: every Worker page opens its one column with Fit AF's logo, linking to /", () => {
  for (const [name, { html }] of Object.entries(pages)) {
    const main = /<body>\n<main class="worker-page">([\s\S]*)<\/main>\n<\/body>/.exec(html)?.[1];
    assert.ok(main, `${name}: the body is one <main class="worker-page">`);
    const logo = /<a class="logo" href="\/"><img src="\/assets\/fitaf-logo\.png" alt="Fit AF" width="88" height="56"><\/a>/;
    assert.match(main, logo, `${name}: the logo, a link to /`);
    const beforeLogo = main.slice(0, main.search(logo)).replace(/<p class="draft">[^<]*<\/p>/, "").trim();
    assert.equal(beforeLogo, "", `${name}: nothing before the logo but the DRAFT line`);
  }
});

test("SP15: the saved offer's one action is the orange button; every other page has none", async () => {
  const action = /<p class="action"><a href="([^"]+)">([^<]+)<\/a><\/p>/g;
  const original = [...pages.original.html.matchAll(action)];
  assert.equal(original.length, 1, "the saved offer: one action");
  assert.equal(original[0][1], "/?e=boston#from-email", "the link back to the page, as § 9.2 ruled");
  for (const [name, { html }] of Object.entries(pages)) {
    if (name !== "original") assert.doesNotMatch(html, /class="action"/, `${name}: no orange button`);
  }
  const sheet = (await readFile(PAGE_CSS, "utf8")).replace(/\/\*[\s\S]*?\*\//g, "");
  const rule = /\.action a\s*\{([^}]*)\}/.exec(sheet)?.[1] ?? "";
  assert.match(rule, /background:\s*var\(--cta\)/, "the store button's orange");
  assert.match(rule, /color:\s*var\(--on-cta\)/);
  assert.ok(Number(/min-height:\s*(\d+)px/.exec(rule)?.[1]) >= 64, "at least 64 px tall");
});

test("SP15: nothing the pages say changes — each page's words and status are cc1d2bb's", async () => {
  const before = await workerPages(base.pkg);
  assert.deepEqual(Object.keys(pages), Object.keys(before));
  for (const name of Object.keys(pages)) {
    assert.equal(pages[name].status, before[name].status, `${name}: its status`);
    assert.equal(pageText(pages[name].html), pageText(before[name].html), `${name}: its words`);
    assert.ok(pageText(before[name].html).length > 10, `control: ${name} has words`);
  }
});

test("SP15: every pair the Worker's pages draw is declared (\"build\": \"worker\") and passes", async () => {
  const { rows, problems } = await measure();
  assert.deepEqual(problems, []);
  const worker = rows.filter((r) => r.build === "worker");
  const has = (fg, bg, role) => worker.some((r) => r.fg === fg && r.bg === bg && r.role === role);
  for (const [fg, bg, role] of [
    ["--ink", "--white", "body"],
    ["--navy", "--white", "body"],
    ["--navy", "--white", "large-text"],
    ["--on-cta", "--cta", "large-text"],
    ["--draft", "--white", "body"],
  ]) assert.ok(has(fg, bg, role), `${fg} on ${bg} (${role})`);
  for (const r of worker) assert.ok(r.pass, `${r.where}: Lc ${r.lc}`);
});
